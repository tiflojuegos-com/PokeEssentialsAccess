# Infinite Fusion's fusion chooser (games/infinitefusion_common/fusion_preview.rb), gamedata pass: each fusion with the
# types, level and unseen tint its screen draws, by verbosity, and the fusions packed from the two Pokemon to fuse.

# The splicers' screen, reduced to the methods the profile hooks, is defined before the file binds to it.
class DoublePreviewScreen
  def initialize(left, right, draw = true)
    @species_left = left
    @species_right = right
    @draw_types = draw
    @draw_level = draw
    @selected = 0
  end

  def drawFusionInformation(_dex_number, _level, _x = 0); nil; end
  def startSelection; @selected; end
  def updateSelectionGraphics; nil; end
  def select(side); @selected = side; updateSelectionGraphics; end
end

fusion_preview = File.join(Harness::ROOT, "games", "infinitefusion_common", "fusion_preview.rb")
eval(Harness.source(fusion_preview), TOPLEVEL_BINDING, fusion_preview)

class IfFusionPreviewGdTest < PokeAccessTest
  Parent = Struct.new(:name)
  Fused = Struct.new(:name, :head_pokemon, :body_pokemon, :type1, :type2, :id_number)
  # A Pokemon of the chooser's other screen, which holds the two to fuse rather than their fusions.
  Mon = Struct.new(:species_data)
  SpeciesData = Struct.new(:id_number)

  # Fusion 1, seen in the Pokedex, of two types; fusion 2, unseen, of one type twice.
  LEFT = Fused.new("Charitoise", Parent.new("Charizard"), Parent.new("Blastoise"), :FIRE, :WATER, 1)
  RIGHT = Fused.new("Blastizard", Parent.new("Blastoise"), Parent.new("Charizard"), :WATER, :WATER, 2)

  test "says the left fusion as the selection starts: head and body, its two types and the level it will have" do
    screen = DoublePreviewScreen.new(LEFT, RIGHT)
    on_screen do
      screen.drawFusionInformation(1, 45, 20)
      screen.startSelection
    end
    assert_equal [[[side_text(LEFT), t(:pdx_type, :t => "TypeFIRE TypeWATER"), t(:if_fusion_level, :n => 45)].join(", "), true]],
                 SpeakCapture.log
  end

  test "says the right fusion as the cursor moves to it: one type for two the same, new to the Pokedex, its tint" do
    screen = DoublePreviewScreen.new(LEFT, RIGHT)
    on_screen do
      screen.drawFusionInformation(2, 45, 270)
      screen.select(1)
    end
    assert_equal [[[side_text(RIGHT), t(:pdx_type, :t => "TypeWATER"), t(:if_fusion_unseen), t(:if_sprite_auto),
                    t(:if_fusion_level, :n => 45)].join(", "), true]], SpeakCapture.log
  end

  test "says neither types nor level on a screen that draws neither" do
    screen = DoublePreviewScreen.new(LEFT, RIGHT, false)
    on_screen do
      screen.drawFusionInformation(1, 30)
      screen.startSelection
    end
    assert_equal [side_text(LEFT)], SpeakCapture.lines
  end

  test "says head and body at brief, the types and the unseen mark from medium, the tint and the level at full" do
    screen = DoublePreviewScreen.new(LEFT, RIGHT)
    screen.drawFusionInformation(2, 45)
    on_disk(screen)
    rows = on_screen { vb_levels { PokeAccess::IFFusionPreview.describe(RIGHT, screen, 1) } }
    medium = [side_text(RIGHT), t(:pdx_type, :t => "TypeWATER"), t(:if_fusion_unseen)]
    assert_equal [side_text(RIGHT), medium.join(", "),
                  (medium + [t(:if_sprite_local), t(:if_fusion_level, :n => 45)]).join(", ")], rows
  end

  test "says what an unseen fusion's tint means: an autogenerated sprite, a custom one not downloaded, one on disk" do
    [[[], false, :if_sprite_auto], [[2], false, :if_sprite_custom], [[2], true, :if_sprite_local],
     [[], true, :if_sprite_local]].each do |customs, local, key|
      screen = DoublePreviewScreen.new(LEFT, RIGHT, false)
      on_disk(screen) if local
      tint = on_screen(customs) { PokeAccess::IFFusionPreview.tint(screen, RIGHT, 1) }
      assert_equal t(key), tint, "custom sprites #{customs.inspect}, on disk #{local}"
    end
  end

  test "gives no tint to a seen fusion, to one off the screen's sides, or where the game cannot tell" do
    screen = DoublePreviewScreen.new(LEFT, RIGHT, false)
    on_screen do
      assert_nil PokeAccess::IFFusionPreview.tint(screen, LEFT, 0), "a seen fusion"
      assert_nil PokeAccess::IFFusionPreview.tint(screen, RIGHT, nil), "no side"
    end
    assert_nil PokeAccess::IFFusionPreview.tint(screen, RIGHT, 1), "no trainer to ask"
  end

  test "packs each side's fusion from the screen's two Pokemon, the left with the first as its head" do
    scene = World.stub_scene(:@poke1 => Mon.new(SpeciesData.new(25)), :@poke2 => Mon.new(SpeciesData.new(4)),
                             :@selected => 0)
    with_nb(576) do
      PokeAccess::IFFusionPreview.focus(scene)
      scene.instance_variable_set(:@selected, 1)
      PokeAccess::IFFusionPreview.focus(scene)
    end
    assert_equal [GameData::Species.get(25 * 576 + 4).name, GameData::Species.get(4 * 576 + 25).name], SpeakCapture.lines
  end

  test "says a fusion held as the engine's own species entry by its name" do
    PokeAccess::IFFusionPreview.focus(World.stub_scene(:@species_left => GameData::Species.get(:B25H4), :@selected => 0))
    assert_equal [[GameData::Species.get(:B25H4).name, true]], SpeakCapture.log
  end

  test "takes a Pokemon the screen holds for no fusion, though it answers for its parents" do
    kinds = with_pokemon_class do |pokemon|
      [PokeAccess::IFFusionPreview.species?(pokemon.new), PokeAccess::IFFusionPreview.species?(LEFT)]
    end
    assert_equal [false, true], kinds
  end

  test "packs with the game's own base, Kanto's 501 where the game sets none" do
    { 576 => 576, nil => 501 }.each do |base, nb|
      assert_equal nb, with_nb(base) { PokeAccess::IFFusionPreview.nb }, "with NB_POKEMON #{base.inspect}"
    end
  end

  private

  def t(key, args = {})
    PokeAccess::I18n.t(key, args)
  end

  # A fusion as said: its name, the parent giving the head and the one giving the body.
  def side_text(fusion)
    t(:if_fusion_side, :name => fusion.name, :head => fusion.head_pokemon.name, :body => fusion.body_pokemon.name)
  end

  # Gives the screen's right sprite a custom picture already on disk.
  def on_disk(screen)
    screen.instance_variable_set(:@sprite_right, Struct.new(:local_path).new("Graphics/CustomBattlers/2.png"))
  end

  # The block's value with the Pokedex having seen fusion 1 only and the game's custom sprite test answering the
  # fusion ids in customs; both put back afterwards.
  def on_screen(customs = [])
    trainer = $Trainer
    seen = Object.new
    def seen.seen?(id); id == 1; end
    $Trainer = seen
    GameFunctions.with(:customSpriteExistsSpecies => lambda { |id| customs.include?(id) }) { yield }
  ensure
    $Trainer = trainer
  end

  # The block's value with the engine's NB_POKEMON set to base, or absent for nil; put back afterwards.
  def with_nb(base)
    had = ::Settings.const_defined?(:NB_POKEMON, false)
    was = had ? ::Settings::NB_POKEMON : nil
    ::Settings.send(:remove_const, :NB_POKEMON) if had
    ::Settings.const_set(:NB_POKEMON, base) if base
    yield
  ensure
    ::Settings.send(:remove_const, :NB_POKEMON) if ::Settings.const_defined?(:NB_POKEMON, false)
    ::Settings.const_set(:NB_POKEMON, was) if had
  end

  # The block's value with the engine's Pokemon class in place, its objects answering for their parents as a fusion
  # does; a class already there is left as it is.
  def with_pokemon_class
    had = Object.const_defined?(:Pokemon, false)
    Object.const_set(:Pokemon, Class.new { def head_pokemon; Parent.new("Charizard"); end }) unless had
    yield ::Pokemon
  ensure
    Object.send(:remove_const, :Pokemon) unless had
  end
end
