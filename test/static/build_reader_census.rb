# Builds ivar_census.txt, loop_census.txt, spec_census.txt and lifecycle_census.txt from the decompiled dumps,
# which are absent on CI (tools/dump_scripts.rb makes one). Run by hand after adding a reader, a profile or a dump:
#   ruby test/static/build_reader_census.rb ["path\to\decompiled Scripts"]
require File.expand_path("reader_sites", File.dirname(__FILE__))

DEFAULT_DUMPS = File.expand_path("../../../../decompiled Scripts", File.dirname(__FILE__))
OUT = File.join(File.dirname(__FILE__), "ivar_census.txt")

dumps = ARGV[0] || ENV["PA_DUMPS"] || DEFAULT_DUMPS
unless File.directory?(dumps)
  puts "dumps folder not found: #{dumps}"
  puts "usage: ruby test/static/build_reader_census.rb [path-to-decompiled-Scripts]"
  exit 1
end

games = Dir.glob(File.join(dumps, "*")).select { |d| File.directory?(d) }.map { |d| File.basename(d) }.sort
if games.empty?
  puts "no game folders under #{dumps}"
  exit 1
end

# Vanilla Essentials joins the survey, so the v22 readers, which no surveyed fangame runs, are checked too.
VANILLA = File.expand_path("../../../../pokemon-essentials/Data/Scripts", File.dirname(__FILE__))
vanilla = ENV["PA_VANILLA"] || VANILLA
sources_of = {}
games.each { |g| sources_of[g] = File.join(dumps, g) }
if File.directory?(vanilla)
  games.push("vanilla")
  sources_of["vanilla"] = vanilla
  games = games.sort
else
  puts "note: vanilla Essentials tree not found at #{vanilla} -- v22 readers stay unverifiable"
end

wanted = {}
ReaderSites.ivars_by_file.each_value { |names| names.each { |n| wanted[n] = {} } }

# One pass per game matching every wanted name at once, read binary (the dumps carry Latin-1 in comments); the
# owning classes are listed too, since a name can be in the game and still on the wrong object.
names = wanted.keys.sort
owners = {}
pattern = /@(#{names.map { |n| Regexp.escape(n) }.join("|")})\b/
games.each do |g|
  profile = ReaderSites::PROFILE_OF[g] || g
  Dir.glob(File.join(sources_of[g], "**", "*.rb")).each do |f|
    stack = ReaderSites::ClassStack.new
    File.open(f, "rb") do |io|
      io.each_line do |line|
        cur = stack.feed(line)
        line.scan(pattern) do
          wanted[$1][profile] = true
          (owners[$1] ||= {})[cur] = true if cur
        end
      end
    end
  end
end

File.open(OUT, "wb") do |io|
  io.print("# GENERATED by test/static/build_reader_census.rb -- do not edit by hand.\n")
  io.print("#\n")
  io.print("# For each instance variable the mod reads off a game object, the profiles whose game actually\n")
  io.print("# has that name anywhere in its scripts. An empty list means NO surveyed game has it, which is\n")
  io.print("# the silent-nil bug this exists to catch: the hook binds, the read answers nil forever.\n")
  io.print("#\n")
  io.print("# format: @name = <profile>, <profile>...  |  <class that has it>, ...\n")
  io.print("# The class list is informational -- the check reads only the profiles before the bar. It is\n")
  io.print("# there because a name can be present in the game and still sit on the WRONG OBJECT, which is a\n")
  io.print("# silent nil just the same, and this turns finding out into one grep.\n")
  io.print("# surveyed profiles (#{games.length}): #{games.map { |g| ReaderSites::PROFILE_OF[g] || g }.sort.join(', ')}\n")
  io.print("# names read: #{names.length} / never found: #{wanted.values.count { |h| h.empty? }}\n")
  names.each do |n|
    klasses = (owners[n] || {}).keys.sort
    shown = (klasses.length > 8) ? klasses[0, 8] + ["+#{klasses.length - 8} more"] : klasses
    io.print("@#{n} = #{wanted[n].keys.sort.join(', ')}#{klasses.empty? ? '' : '  |  ' + shown.join(', ')}\n")
  end
end

puts "wrote #{OUT}: #{names.length} ivar names across #{games.length} games"
missing = names.select { |n| wanted[n].empty? }
puts "never found in any dump (#{missing.length}): #{missing.join(', ')}" unless missing.empty?

# Second census: which after-hooked methods are the screen's blocking loop (an after hook there speaks only on the
# way out). A method blocks when it loops (LOOP_FORM) and pumps the frame (PUMP_FORM), directly or through its last
# statement; `for` is left out of LOOP_FORM on purpose: its only hits were false positives.
LOOP_OUT = File.join(File.dirname(__FILE__), "loop_census.txt")
LOOP_FORM = /^\s*(?:loop\s+do|while\b|until\b)/
PUMP_FORM = /\b(?:Graphics\.update|pbUpdate|pbGraphicsUpdate)\b/

hooked = {}
ReaderSites.after_hooks_by_file.each_value { |sites| sites.each { |s| hooked[s] = {} } }
hooked_classes = {}
hooked.each_key { |s| hooked_classes[s.split("#").first.split("::").last] = true }

# A census key shortened to its last namespace segment, the only name a decompiled class line reliably carries.
def short_key(key)
  cls, meth = key.split("#", 2)
  "#{cls.split('::').last}##{meth}"
end

# evidence: the Class#method pairs some dump defines, keyed by the defining class; seen: the hook keys some game
# answered for, on the class, an ancestor or Object. A site nothing defines is printed as NO-DUMP, not as clean.
# - the superclass lines are collected first, so evidence covers a hooked class's ancestors too.
# - attr_* lines count as method definitions with no body, so they never match a blocking loop.
# - a def at file scope files under Object, as Ruby resolves it.
# - a method's body runs to its own `end` or the next `def`, whichever comes first; a mismatched `end` indent or a
#   nested def can truncate it early, which misses a loop rather than inventing one.
# - a method counts as indirection only through its last statement, an optional trailing if/unless included.
# - an unresolved method name is looked up through its class's superclass chain, then Object.
evidence = {}
seen = {}

games.each do |g|
  profile = ReaderSites::PROFILE_OF[g] || g
  direct = {}
  calls = {}
  supers = {}
  Dir.glob(File.join(sources_of[g], "**", "*.rb")).each do |f|
    src = File.open(f, "rb") { |io| io.read }
    src.scan(/^\s*class\s+([A-Z][A-Za-z0-9_:]*)\s*<\s*([A-Z][A-Za-z0-9_:]*)/) { |a, b| supers[a.split("::").last] = b.split("::").last }
  end
  wanted = {}
  hooked_classes.each_key do |c|
    cur = c
    6.times do
      wanted[cur] = true
      cur = supers[cur]
      break if cur.nil?
    end
  end
  Dir.glob(File.join(sources_of[g], "**", "*.rb")).each do |f|
    stack = ReaderSites::ClassStack.new
    lines = File.open(f, "rb") { |io| io.readlines }
    lines.each_with_index do |line, i|
      cur = stack.feed(line)
      if cur && line =~ /^\s*attr_(accessor|reader|writer)\s+(.+)$/
        kind = $1
        $2.scan(/:([a-zA-Z_]\w*)/) do
          evidence["#{cur}##{$1}"] = true unless kind == "writer"
          evidence["#{cur}##{$1}="] = true unless kind == "reader"
        end
      end
      next if line =~ /^\s*(?:class|module)\s+[A-Z]/
      next unless line =~ /^(\s*)def\s+(?:self\.)?([a-zA-Z_]\w*[?!=]?)/
      indent = $1.length
      meth = $2
      cur = stack.owner_at(indent) || cur
      cur = "Object" if cur.nil? && indent == 0
      next unless cur && (wanted[cur] || cur == "Object")
      body = []
      j = i + 1
      while j < lines.length
        break if lines[j] =~ /^\s*def\s/
        break if lines[j] =~ /^\s{#{indent}}end\b/ && lines[j][/^\s*/].length == indent
        body.push(lines[j])
        j += 1
      end
      text = body.join
      key = "#{cur}##{meth}"
      evidence[key] = true
      direct[key] = true if text =~ LOOP_FORM && text =~ PUMP_FORM
      tail =body.reverse.find { |l| l.strip != "" && l.strip != "end" }
      m = tail.to_s.match(/^\s*(?:self\.)?([a-z_]\w*)\s*(?:(?:if|unless)\s+\S.*)?$/)
      calls[key] = m ? ["#{cur}##{m[1]}"] : []
    end
  end
  aliases =lambda do |s|
    cls, meth = s.split("#", 2)
    out = [s]
    5.times do
      cls = supers[cls]
      break if cls.nil? || out.include?("#{cls}##{meth}")
      out.push("#{cls}##{meth}")
    end
    out.push("Object##{meth}")
    out
  end
  hooked.each_key do |key|
    names = aliases.call(short_key(key))
    hooked[key][profile] = true if names.any? { |k| direct[k] || (calls[k] || []).any? { |c| direct[c] } }
    seen[key] = true if names.any? { |k| evidence[k] }
  end
end

no_evidence = hooked.keys.sort.reject { |k| seen[k] }
unresolved = ReaderSites.unresolved_after_sites

File.open(LOOP_OUT, "wb") do |io|
  io.print("# GENERATED by test/static/build_reader_census.rb -- do not edit by hand.\n")
  io.print("#\n")
  io.print("# For each Class#method the mod binds an AFTER hook to, the profiles whose copy of that method is\n")
  io.print("# the screen's own blocking loop -- it loops and pumps Graphics.update, directly or through one\n")
  io.print("# call. An after hook on one of those runs when the player LEAVES the screen, so the reader is\n")
  io.print("# silent the whole time it is open. A non-empty list is the bug; the answer is around + a poll.\n")
  io.print("#\n")
  io.print("#\n")
  io.print("# format: Class#method = <profile>, <profile>...\n")
  io.print("# surveyed sources (#{games.length}): #{games.map { |g| ReaderSites::PROFILE_OF[g] || g }.sort.join(', ')}\n")
  io.print("# A row marked NO-DUMP is one no surveyed game defines: it was not checked and found clean, it\n")
  io.print("# could not be checked at all. The two used to print identically, which made a sixth of the file\n")
  io.print("# read as evidence it was not.\n")
  io.print("# after-style hook sites: #{hooked.length} / blocking somewhere: #{hooked.values.count { |h| !h.empty? }}")
  io.print(" / no dump defines it: #{no_evidence.length}\n")
  io.print("# after-style sites the extractor cannot resolve (computed class or method): #{unresolved.values.flatten.length}\n")
  hooked.keys.sort.each do |k|
    io.print("#{k} = #{no_evidence.include?(k) ? 'NO-DUMP' : hooked[k].keys.sort.join(', ')}\n")
  end
  io.print("\n")
  io.print("# UNRESOLVED: registered with a computed class or method, so the blocking check never saw them.\n")
  unresolved.keys.sort.each do |path|
    unresolved[path].each { |l| io.print("# #{path}: #{l}\n") }
  end
end

blocking = hooked.keys.sort.select { |k| !hooked[k].empty? }
puts "wrote #{LOOP_OUT}: #{hooked.length} after-hook sites, #{blocking.length} blocking, " +
     "#{no_evidence.length} with no dump, #{unresolved.values.flatten.length} unresolved"
puts "blocking: #{blocking.join(', ')}" unless blocking.empty?

# Third census: every *_spec.rb run_all must discover, so a sweep whose glob went quiet fails; needs no dumps.
SPEC_OUT = File.join(File.dirname(__FILE__), "spec_census.txt")
test_root = File.expand_path(File.join(File.dirname(__FILE__), ".."))
spec_rel = Dir.glob(File.join(test_root, "{unit,behavior,static}", "**", "*_spec.rb"))
              .map { |p| File.expand_path(p)[(test_root.length + 1)..-1].tr("\\", "/") }.sort
File.open(SPEC_OUT, "wb") do |io|
  io.print("# Spec files run_all must discover. Regenerate: ruby test/static/build_reader_census.rb\n")
  spec_rel.each { |r| io.print(r, "\n") }
end
puts "wrote #{SPEC_OUT}: #{spec_rel.length} spec files"

# Fourth census: per scene InfoWindow watches, the lifecycle methods the games define and those the mod declares,
# which must meet; class names listed through variants or scene_classes count, and an :open constant is resolved.
LIFE_OUT = File.join(File.dirname(__FILE__), "lifecycle_census.txt")
LIFE_RE = /\A(?:pbStart[A-Za-z]*|pbEnd[A-Za-z]*|start|main)\z/
DEFAULT_OPENERS = %w[pbStartScene start]
MOD_ROOT = File.expand_path("../..", File.dirname(__FILE__))

mod_files = %w[core games plugins].map { |d| Dir.glob(File.join(MOD_ROOT, d, "**", "*.rb")) }.flatten.sort
mod_src = {}
mod_files.each { |f| mod_src[f] = File.read(f).gsub(/^\s*#.*/, "") }

# The openers a constant carries, so a call that passes one can be followed: CONST = [:a, :b] gives the
# list itself, CONST = { :open => [:a, :b], ... } gives its :open list.
OPEN_LIST = /:open\s*=>\s*(?:\[([^\]]*)\]|:([a-z_][A-Za-z0-9_]*))/
def symbols_in(text); text.to_s.scan(/(?<!:):([a-z_][A-Za-z0-9_]*)/).flatten; end
const_opens = {}
mod_src.each_value do |src|
  src.scan(/\b([A-Z][A-Z0-9_]+)\s*=\s*\[([^\]]*)\]/) { |name, body| const_opens[name] = symbols_in(body) }
  src.scan(/\b([A-Z][A-Z0-9_]+)\s*=\s*\{([^}]*)\}/) do |name, body|
    m = body.match(OPEN_LIST)
    const_opens[name] = m ? symbols_in(m[1] || ":#{m[2]}") : [] if m
  end
end

# One InfoWindow.watch call with its arguments (one level of nested parentheses): its class is the first argument
# when literal, else the file's variants/scene_classes spellings; its openers, the defaults plus the declared ones.
WATCH_CALL = /\bInfoWindow\.watch\(((?:[^()]|\([^()]*\))*)\)/m
watched = {}
mod_src.each do |f, src|
  next unless src =~ /\bInfoWindow\.watch\(/
  listed = []
  [/\bvariants\(\s*\[([^\]]*)\]/, /\bscene_classes\(([^)]*)\)/].each do |re|
    src.scan(re) { |m| listed += m[0].scan(/"([A-Z][A-Za-z0-9_:]*)"/).flatten }
  end
  src.scan(WATCH_CALL) do |m|
    args = m[0]
    names = (args =~ /\A\s*"([A-Z][A-Za-z0-9_:]*)"/) ? [$1] : listed
    opens = DEFAULT_OPENERS.dup
    args.scan(OPEN_LIST) { |lst, one| opens += symbols_in(lst || ":#{one}") }
    args.scan(/\b([A-Z][A-Z0-9_]+)\b/) { |c| opens += (const_opens[c[0]] || []) }
    names.uniq.each do |c|
      watched[c] ||= { :declared => [], :games => {} }
      watched[c][:declared] = (watched[c][:declared] + opens).uniq
    end
  end
end

games.each do |g|
  Dir.glob(File.join(sources_of[g], "**", "*.rb")).each do |path|
    src = File.open(path, "rb") { |io| io.read }
    stack = ReaderSites::ClassStack.new
    src.each_line do |line|
      stack.feed(line)
      next unless line =~ /^(\s*)def\s+([a-zA-Z_][A-Za-z0-9_]*)/
      indent = $1.length
      meth = $2
      next unless meth =~ LIFE_RE
      cur = stack.owner_at(indent)
      (watched[cur][:games][meth] ||= {})[g] = true if cur && watched.has_key?(cur)
    end
  end
end

File.open(LIFE_OUT, "wb") do |io|
  io.print("# GENERATED by test/static/build_reader_census.rb -- do not edit by hand.\n")
  io.print("#\n")
  io.print("# Per InfoWindow-watched scene: the lifecycle methods the MOD declares (its :open list plus the\n")
  io.print("# engine defaults) and the ones the surveyed GAMES define on that class. A watch whose two sets\n")
  io.print("# do not meet binds nothing: the screen is never entered and every window on it is dead, with\n")
  io.print("# the class present, the windows present and nothing anywhere to show for it.\n")
  io.print("# format: Class = declared:a|b ; games:a(n),b(n)   -- an empty games list means no source has it\n")
  io.print("# surveyed sources (#{games.length}): #{games.sort.join(', ')}\n")
  watched.keys.sort.each do |c|
    rows = watched[c][:games].keys.sort.map { |m| "#{m}(#{watched[c][:games][m].length})" }
    io.print("#{c} = declared:#{watched[c][:declared].sort.join('|')} ; games:#{rows.join(',')}\n")
  end
end
dead = watched.keys.select { |c| !watched[c][:games].empty? && (watched[c][:declared] & watched[c][:games].keys).empty? }
puts "wrote #{LIFE_OUT}: #{watched.length} watched scenes, #{dead.length} declared against a lifecycle no game has"
puts "sin ciclo de vida: #{dead.join(', ')}" unless dead.empty?
